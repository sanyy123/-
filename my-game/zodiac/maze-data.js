// ===== 迷宫常量 =====
const MAZE_CONFIG = {
  HP: 5,
  HP_REWARD_PER_LEFT: 20,
  INVINCIBLE_MS: 2000,
  FOOD_NORMAL: 10,
  FOOD_GOLD: 30,
  FOOD_GEM: 50,
  FOOD_DIAMOND: 80
};

const MAZE_HIGHSCORE_PREFIX = 'mazeHighScoreV1_level';
const MAZE_CLEARED_KEY = 'mazeClearedV1';

function getLevelMaxScore(level) {
  if (!level) return 0;
  let foodScore = 0;
  for (let y = 0; y < level.rows; y++) {
    const row = level.map[y];
    for (let x = 0; x < level.cols; x++) {
      const ch = row[x];
      if (ch === '1') foodScore += MAZE_CONFIG.FOOD_NORMAL;
      else if (ch === '2') foodScore += MAZE_CONFIG.FOOD_GOLD;
      else if (ch === '3') foodScore += MAZE_CONFIG.FOOD_GEM;
      else if (ch === '4') foodScore += MAZE_CONFIG.FOOD_DIAMOND;
    }
  }
  return foodScore + MAZE_CONFIG.HP * MAZE_CONFIG.HP_REWARD_PER_LEFT;
}

